# gunicorn.conf.py
bind = "0.0.0.0:5000"          # Привязка к порту и хосту
workers = 4                    # Количество рабочих процессов (рекомендуется на основе ядер CPU)
worker_class = "sync"          # Используем синхронные workers (по умолчанию)
timeout = 120                  # Таймаут на обработку запроса (сек)
keepalive = 5                  # Поддержание соединений (сек)
max_requests = 1000            # Перезапуск worker после обработки N запросов
max_requests_jitter = 50       # Случайная задержка для равномерной нагрузки
limit_request_line = 4094      # Безопасный лимит для длины строки запроса
limit_request_fields = 100     # Лимит полей в запросе
limit_request_field_size = 8190 # Лимит размера поля в запросе (RFC 7230)
